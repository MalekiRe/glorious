use std::path::Path;

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};

use crate::util::valid_package_name;

pub const LOCK_NAME: &str = "grandiose.lock";

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    #[serde(default, rename = "package")]
    pub packages: Vec<LockedPackage>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub name: String,
    pub source: String,
    /// Full commit sha; absent for path dependencies.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub commit: Option<String>,
    /// `blake3:<hex>` over the package's source set; absent for path deps
    /// (the local working tree is allowed to change freely).
    #[serde(skip_serializing_if = "Option::is_none", rename = "content-hash")]
    pub content_hash: Option<String>,
    pub deps: Vec<String>,
}

impl Lockfile {
    pub fn load(path: &Path) -> Result<Option<Lockfile>> {
        if !path.exists() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(path)
            .with_context(|| format!("could not read {}", path.display()))?;
        let lock: Lockfile =
            toml::from_str(&text).with_context(|| format!("could not parse {}", path.display()))?;
        if lock.version != 1 {
            bail!(
                "{}: unsupported lockfile version {}",
                path.display(),
                lock.version
            );
        }
        let mut identities = std::collections::BTreeSet::new();
        for package in &lock.packages {
            if !valid_package_name(&package.name) {
                bail!(
                    "{}: invalid locked package name `{}`",
                    path.display(),
                    package.name
                );
            }
            if !identities.insert((&package.name, &package.source)) {
                bail!(
                    "{}: duplicate lock entry for `{}` from `{}`",
                    path.display(),
                    package.name,
                    package.source
                );
            }
            for dependency in &package.deps {
                if !valid_package_name(dependency) {
                    bail!(
                        "{}: `{}` has invalid dependency name `{dependency}`",
                        path.display(),
                        package.name
                    );
                }
            }
            if package.source.starts_with("git+") {
                let commit = package.commit.as_deref().with_context(|| {
                    format!(
                        "{}: git package `{}` has no commit",
                        path.display(),
                        package.name
                    )
                })?;
                if !matches!(commit.len(), 40 | 64)
                    || !commit.bytes().all(|byte| byte.is_ascii_hexdigit())
                {
                    bail!(
                        "{}: git package `{}` has an invalid commit",
                        path.display(),
                        package.name
                    );
                }
                let hash = package.content_hash.as_deref().with_context(|| {
                    format!(
                        "{}: git package `{}` has no content hash",
                        path.display(),
                        package.name
                    )
                })?;
                let digest = hash.strip_prefix("blake3:").unwrap_or_default();
                if digest.len() != 64 || !digest.bytes().all(|byte| byte.is_ascii_hexdigit()) {
                    bail!(
                        "{}: git package `{}` has an invalid content hash",
                        path.display(),
                        package.name
                    );
                }
            } else if !package.source.starts_with("path+") {
                bail!(
                    "{}: package `{}` has an invalid source id",
                    path.display(),
                    package.name
                );
            }
        }
        Ok(Some(lock))
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        let mut sorted = self.clone();
        sorted.packages.sort_by(|a, b| a.name.cmp(&b.name));
        let header =
            "# Generated by grand; commit this file. Edit via `grand add` / `grand update`.\n";
        let body = toml::to_string_pretty(&sorted).context("serializing lockfile")?;
        std::fs::write(path, format!("{header}{body}"))
            .with_context(|| format!("could not write {}", path.display()))?;
        Ok(())
    }

    pub fn find(&self, name: &str, source: &str) -> Option<&LockedPackage> {
        self.packages
            .iter()
            .find(|p| p.name == name && p.source == source)
    }
}
